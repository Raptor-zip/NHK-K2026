#   下の判定（進み角 < 摩擦角）が成立しなくなる。
#   → z1 = 1, z2 = 40。
#
#   モジュールは
#     ・ホイール外径がローラー軸（仰角軸から 45.75mm、φ12 なので手前 39.75mm）
#       に当たらないこと … 歯先半径 < 39.75
#     ・歯が持つこと … 下の歯元曲げ応力
#   の 2 つで決まる。m=1.5 なら基準円 φ60・歯先 φ63（半径 31.5）で
#   ローラー軸まで 8.25mm 空く。m=2.0 だと歯先 φ84（半径 42）で軸を貫く。
#   ⚠ 以前は「φ80 のホイール」と書きながら図は φ68 の**ただの円筒**で、
