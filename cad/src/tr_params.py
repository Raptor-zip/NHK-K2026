#   落ちて自重で仰角が下がる。給脂はグリス（二硫化モリブデン）に限る。**
#   ⚠ セルフロックは**静止摩擦**に頼るので、走行振動が乗ると滑ることがある。
#     自重側の逆駆動トルクは 1.78N·m（scripts/fasteners.py J10）と小さいが、
#     制御側では「射出の瞬間だけ保持電流を流す」を前提にすること。
