#   X=±150 では |Y| > 56 でリングの外に出る。56 ちょうどだと頭が
#   リングに 199mm³ 刺さる。70 まで逃がす。
# ⚠ ボルトは**リングの外・台座プレートの中**でなければならない。
#     旋回リング   半径 140..160（全周）
#     歯付きリング 半径 158..178（+X 側だけの扇形）
#     台座プレート 半径 138..185
#   -X 側（X=-150）は歯付きリングが無いので r 160..185 → |Y| 55.7..108.3
#   +X 側（X=+125）は歯付きリングを避けて r 178..185 → |Y| 126.7..136.4
PEDESTAL_BOLTS = tuple((bx, sy * d)
                       # ⚠ 同じ梁に 2 本並べるとき、ピッチは**ワッシャの外径**
                       #   より大きく取る。M5+ワッシャは φ10.5 なので、
                       #   8mm ピッチ（128/136）ではワッシャ同士が 2.5mm
                       #   重なっていた。11mm 取る。
                       #   さらに +X 側は歯付きリング（外径 r178）の下へ
                       #   頭が潜らない半径に収める（中心 r + 5.25 ≤ 178
                       #   → |Y| ≤ 129 で r 179.6、皿ねじ相当の頭で成立）。
                       for bx, ds in zip(PEDESTAL_BEAM_X, ((72.0, 100.0), (118.0, 129.0)))
                       for sy in (1, -1) for d in ds)
PEDESTAL_RING_R = 185.0     # 台座リングプレート外半径（旋回リング Ø320 を受ける）
PEDESTAL_BORE_R = 138.0     # 同 内半径（ローラー占有半径 91 + 逃げ）
