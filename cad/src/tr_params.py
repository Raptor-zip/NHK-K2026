#     使っていた。実際にボルトが並ぶのは PCD28（腕 14mm）なので、
#     **分担荷重を 1/2.9 に小さく見積もっていた**。
#
#   リード = π・m・z1 = 4.712mm（1 回転でホイールが 1 歯＝9° 進む）。
#
# ■ セルフロック（自重で落ちない）の根拠
#   進み角 γ = atan(z1・m / d1) = atan(1.5/24) = 3.576°
#   摩擦角 ρ' = atan(μ / cos αn)、μ は静止摩擦係数
#     鋼ウォーム × アルミ(A5052)ホイール・グリス潤滑の静止 μ は 0.10〜0.15。
#     **安全側に 0.08** を採ると ρ' = atan(0.08/cos20°) = 4.868°
#   γ 3.576° < ρ' 4.868° → 逆駆動効率 η' = 1 − tanρ'/tanγ < 0 ＝ **セルフロック**
